#!/usr/bin/env python3
"""Generate the LVGL 7 assets of the Slovingo app (fonts, icon and mascots).

lv_font_conv is not needed: the font is written straight from a TTF with
Pillow (FreeType) in the plain lv_font_fmt_txt format (no kerning, no
compression). The default Ubuntu_* fonts of this firmware only cover
U+20..U+7E and U+A0..U+FF; Slovak also needs c-caron, d-caron, l-acute,
l-caron, n-caron, r-acute, s-caron, t-caron, z-caron..., so the fonts below
cover Basic Latin + Latin-1 + Latin Extended-A (U+20..U+17F).

Usage (from the repository root, needs Pillow and DejaVu Sans):
    python3 src/app/slovingo/tools/gen_assets.py

The fonts are derived from DejaVu Sans (free licence, see
https://dejavu-fonts.github.io/License.html).
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

APP_DIR = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
TTF_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

# (first code point, last code point), one FORMAT0_TINY cmap each
RANGES = [(0x20, 0x7E), (0xA0, 0x17F)]
BPP = 4
SIZES = (16, 22)


def glyph_bitmap(font, ch):
    """Return (bytes, box_w, box_h, ofs_x, ofs_y, adv_w) for one character."""
    adv_w = int(round(font.getlength(ch) * 16))
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return b"", 0, 0, 0, 0, adv_w
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, fill=255, font=font, anchor="ls")
    levels = (1 << BPP) - 1
    bits = []
    for px in img.get_flattened_data():
        bits.append(round(px * levels / 255))
    # pack MSB first, rows are NOT byte aligned, pad at the end of the glyph
    out = bytearray()
    acc = nbits = 0
    for v in bits:
        acc = (acc << BPP) | v
        nbits += BPP
        while nbits >= 8:
            out.append((acc >> (nbits - 8)) & 0xFF)
            nbits -= 8
    if nbits:
        out.append((acc << (8 - nbits)) & 0xFF)
    return bytes(out), w, h, x0, -y1, adv_w


def write_font(size):
    name = "slovingo_%dpx" % size
    font = ImageFont.truetype(TTF, size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    bitmaps, descs = bytearray(), [(0, 0, 0, 0, 0, 0)]  # glyph id 0 is reserved
    cmaps, first_id = [], 1
    for lo, hi in RANGES:
        cmaps.append((lo, hi - lo + 1, first_id))
        for cp in range(lo, hi + 1):
            data, w, h, ox, oy, adv = glyph_bitmap(font, chr(cp))
            descs.append((len(bitmaps) if data else 0, adv, w, h, ox, oy))
            bitmaps += data
        first_id += hi - lo + 1

    guard = name.upper()
    lines = [
        "// Generated by tools/gen_assets.py from DejaVu Sans, do not edit.",
        '#include "lvgl.h"',
        "",
        "#ifndef %s" % guard, "#define %s 1" % guard, "#endif", "",
        "#if %s" % guard, "",
        "static LV_ATTRIBUTE_LARGE_CONST const uint8_t gylph_bitmap[] = {",
    ]
    for i in range(0, len(bitmaps), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in bitmaps[i:i + 16]) + ",")
    if not bitmaps:
        lines.append("    0x00")
    lines += ["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {"]
    for i, (bi, adv, w, h, ox, oy) in enumerate(descs):
        lines.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}%s"
                     % (bi, adv, w, h, ox, oy, ("," if i < len(descs) - 1 else "")))
    lines += ["};", "", "static const lv_font_fmt_txt_cmap_t cmaps[] = {"]
    for i, (start, length, gid) in enumerate(cmaps):
        lines.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = %d, .unicode_list = NULL,"
                     " .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}%s"
                     % (start, length, gid, ("," if i < len(cmaps) - 1 else "")))
    lines += [
        "};", "",
        "static lv_font_fmt_txt_dsc_t font_dsc = {",
        "    .glyph_bitmap = gylph_bitmap,", "    .glyph_dsc = glyph_dsc,", "    .cmaps = cmaps,",
        "    .kern_dsc = NULL,", "    .kern_scale = 0,", "    .cmap_num = %d," % len(cmaps),
        "    .bpp = %d," % BPP, "    .kern_classes = 0,", "    .bitmap_format = 0", "};", "",
        "lv_font_t %s = {" % name,
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
        "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        "    .line_height = %d," % (ascent + descent),
        "    .base_line = %d," % descent,
        "#if !(LVGL_VERSION_MAJOR == 6 && LVGL_VERSION_MINOR == 0)",
        "    .subpx = LV_FONT_SUBPX_NONE,",
        "#endif",
        "    .dsc = &font_dsc",
        "};", "", "#endif /* %s */" % guard, "",
    ]
    path = os.path.join(APP_DIR, "font", name + ".c")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("%s: %d glyphs, %d bitmap bytes" % (path, len(descs) - 1, len(bitmaps)))


def draw_icon(size):
    """The fox (happy) on the blue of the Slovak flag, with a small speech bubble."""
    big = size * 8
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((big * 0.04, big * 0.04, big * 0.96, big * 0.96), radius=big * 0.22, fill=(11, 78, 162, 255))
    # tricolour band at the bottom: white, blue, red
    band = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    bd = ImageDraw.Draw(band)
    bd.rectangle((0, big * 0.80, big, big * 0.853), fill=(255, 255, 255, 255))
    bd.rectangle((0, big * 0.853, big, big * 0.906), fill=(40, 110, 210, 255))
    bd.rectangle((0, big * 0.906, big, big), fill=(238, 28, 37, 255))
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).rounded_rectangle((big * 0.04, big * 0.04, big * 0.96, big * 0.96), radius=big * 0.22, fill=255)
    img.paste(band, (0, 0), Image.composite(band.split()[3], Image.new("L", (big, big), 0), mask))
    icon = img.resize((size, size), Image.LANCZOS)
    fox = draw_fox("happy", int(size * 0.74))
    icon.alpha_composite(fox, ((size - fox.width) // 2, int(size * 0.07)))
    return icon


def write_image(name, img):
    px = list(img.get_flattened_data())
    size_w, size_h = img.size

    def fmt8(r, g, b, a):
        return [(r >> 5) << 5 | (g >> 5) << 2 | (b >> 6), a]

    def fmt16(r, g, b, a, swap=False):
        v = (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)
        lo, hi = v & 0xFF, v >> 8
        return ([hi, lo] if swap else [lo, hi]) + [a]

    variants = [
        ("LV_COLOR_DEPTH == 1 || LV_COLOR_DEPTH == 8", "Blue: 2 bit, Green: 3 bit, Red: 3 bit, Alpha 8 bit", fmt8),
        ("LV_COLOR_DEPTH == 16 && LV_COLOR_16_SWAP == 0", "Blue: 5 bit, Green: 6 bit, Red: 5 bit, Alpha 8 bit", fmt16),
        ("LV_COLOR_DEPTH == 16 && LV_COLOR_16_SWAP != 0", "same, the 2 colour bytes swapped", lambda *p: fmt16(*p, swap=True)),
        ("LV_COLOR_DEPTH == 32", "Blue, Green, Red, Alpha", lambda r, g, b, a: [b, g, r, a]),
    ]
    out = [
        "// Generated by tools/gen_assets.py, do not edit.",
        "#if defined(LV_LVGL_H_INCLUDE_SIMPLE)", '#include "lvgl.h"', "#else", '#include "../lvgl/lvgl.h"', "#endif", "",
        "#ifndef LV_ATTRIBUTE_MEM_ALIGN", "#define LV_ATTRIBUTE_MEM_ALIGN", "#endif", "",
        "#ifndef LV_ATTRIBUTE_IMG_%s" % name.upper(), "#define LV_ATTRIBUTE_IMG_%s" % name.upper(), "#endif", "",
        "const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_IMG_%s uint8_t %s_map[] = {" % (name.upper(), name),
    ]
    for cond, comment, fn in variants:
        out += ["#if " + cond, "  /*Pixel format: %s*/" % comment]
        data = [b for p in px for b in fn(*p)]
        for i in range(0, len(data), 20):
            out.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
        out.append("#endif")
    out += [
        "};", "",
        "const lv_img_dsc_t %s = {" % name,
        "  .header.always_zero = 0,", "  .header.w = %d," % size_w, "  .header.h = %d," % size_h,
        "  .data_size = %d * LV_IMG_PX_SIZE_ALPHA_BYTE," % (size_w * size_h),
        "  .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,", "  .data = %s_map," % name, "};", "",
    ]
    path = os.path.join(APP_DIR, "images", name + ".c")
    with open(path, "w") as f:
        f.write("\n".join(out))
    img.save(os.path.join(APP_DIR, "tools", name + "_preview.png"))
    print(path)


def write_icon(size):
    write_image("slovingo_%dpx" % size, draw_icon(size))


# ---------------------------------------------------------------------------
# mascots: the fox (the player, "Liska") and the rabbit (Andrea).
# mood: neutral, happy or sad.
# ---------------------------------------------------------------------------

# The mascots are the ones of the web version (Slovingo engine, _site/mascots/*.svg),
# rendered once to 512 px PNGs in tools/mascots/ and reduced here: cropped to the
# drawing, fitted in a square and sharpened a little so the faces stay readable at
# 40 and 64 px.
MASCOT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "mascots")
MOODS = {"happy": "content", "sad": "comfort", "neutral": "think"}


def _mascot(animal, mood, size):
    src = Image.open(os.path.join(MASCOT_DIR, "%s-%s.png" % (animal, MOODS[mood]))).convert("RGBA")
    src = src.crop(src.getbbox())
    scale = size / max(src.size)
    w, h = max(1, round(src.width * scale)), max(1, round(src.height * scale))
    # work on premultiplied colours so the transparent edge does not darken the outline
    small = src.convert("RGBa").resize((w, h), Image.LANCZOS).convert("RGBA")
    small = small.filter(ImageFilter.UnsharpMask(radius=0.6, percent=60, threshold=0))
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    img.alpha_composite(small, ((size - w) // 2, size - h if animal == "rabbit" else (size - h) // 2))
    return img


def draw_fox(mood, size):
    return _mascot("fox", mood, size)


def draw_rabbit(mood, size):
    return _mascot("rabbit", mood, size)


# ---------------------------------------------------------------------------
# series pictograms: the emoji of the series themes (the themes of the HTML site,
# subgroup_themes of lang.json), taken from Noto Color Emoji (SIL OFL) and reduced to
# 32 px. THEME_ICONS is the list of the C code (slv_themes[] of slovingo_app_main.cpp).
# ---------------------------------------------------------------------------

EMOJI_TTF = "/usr/share/fonts/truetype/noto/NotoColorEmoji.ttf"
THEME_ICON_SIZE = 32
THEME_ICONS = [
    ("default", "\U0001F4DA"),     # books
    ("basics", "\U0001F9F0"),      # toolbox
    ("family", "\U0001F469\U0001F467"),  # a woman and a girl, side by side (the family emoji of Noto is a grey keycap)
    ("house", "\U0001F3E0"),       # house
    ("food", "\U0001F372"),        # pot of food
    ("time", "\U0001F550"),        # clock
    ("shopping", "\U0001F6D2"),    # shopping cart
    ("city", "\U0001F3D9"),        # cityscape
    ("weather", "\U0001F326"),     # sun behind rain cloud
    ("mountains", "\U0001F3D4"),   # snow-capped mountain
    ("easter", "\U0001F95A"),      # egg
    ("animals", "\U0001F98C"),     # deer
    ("games", "\U0001F3B2"),       # dice
    ("sea", "\U0001F30A"),         # wave
]


def _emoji_glyph(char):
    font = ImageFont.truetype(EMOJI_TTF, 109)
    glyph = Image.new("RGBA", (160, 160), (0, 0, 0, 0))
    ImageDraw.Draw(glyph).text((10, 10), char, font=font, embedded_color=True)
    return glyph.crop(glyph.getbbox())


def draw_theme_icon(char, size):
    if len(char) == 2:
        # two emoji side by side: the first one big, the second smaller and lower
        big = _emoji_glyph(char[0])
        little = _emoji_glyph(char[1])
        canvas = Image.new("RGBA", (200, 160), (0, 0, 0, 0))
        big = big.resize((int(big.width * 0.95), int(big.height * 0.95)), Image.LANCZOS)
        little = little.resize((int(little.width * 0.65), int(little.height * 0.65)), Image.LANCZOS)
        canvas.alpha_composite(big, (0, 0))
        canvas.alpha_composite(little, (big.width - 12, big.height - little.height))
        glyph = canvas.crop(canvas.getbbox())
    else:
        glyph = _emoji_glyph(char)
    scale = size / max(glyph.size)
    w, h = max(1, round(glyph.width * scale)), max(1, round(glyph.height * scale))
    small = glyph.convert("RGBa").resize((w, h), Image.LANCZOS).convert("RGBA")
    small = small.filter(ImageFilter.UnsharpMask(radius=0.5, percent=40, threshold=0))
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    img.alpha_composite(small, ((size - w) // 2, (size - h) // 2))
    return img


# (name, drawing function, mood, size)
MASCOTS = [
    ("slv_fox_neutral_40", draw_fox, "neutral", 40),
    ("slv_fox_happy_40", draw_fox, "happy", 40),
    ("slv_fox_sad_40", draw_fox, "sad", 40),
    ("slv_fox_happy_64", draw_fox, "happy", 64),
    ("slv_fox_sad_64", draw_fox, "sad", 64),
    ("slv_rabbit_happy_64", draw_rabbit, "happy", 64),
]


if __name__ == "__main__":
    if not os.path.exists(TTF):
        sys.exit("DejaVu Sans not found at " + TTF)
    for s in SIZES:
        write_font(s)
    write_icon(64)
    for name, draw, mood, size in MASCOTS:
        write_image(name, draw(mood, size))
    if os.path.exists(EMOJI_TTF):
        for key, char in THEME_ICONS:
            write_image("slv_theme_%s_%d" % (key, THEME_ICON_SIZE), draw_theme_icon(char, THEME_ICON_SIZE))
    else:
        print("Noto Color Emoji not found at %s, the series pictograms are kept as they are" % EMOJI_TTF)
